'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict'),path=require('path');
const dir=__dirname;const js=fs.readFileSync(path.join(dir,'aplicativo.js'),'utf8');
const prefix=js.slice(0,js.indexOf('function renderIntro()'));
const ctx=vm.createContext({document:{querySelector:()=>({})},console});
for(const f of ['dados.js','metadados.js','motor.js']) vm.runInContext(fs.readFileSync(path.join(dir,f),'utf8'),ctx,{filename:f});
vm.runInContext(prefix,ctx);
const q=()=>JSON.parse(vm.runInContext('JSON.stringify(questions())',ctx));
const set=(k,v)=>vm.runInContext(`setAnswer(${JSON.stringify(k)},${JSON.stringify(v)})`,ctx);
const opts=key=>q().find(x=>x.key===key)?.opts.map(x=>x[1]);
const D=vm.runInContext('CINE_DATA',ctx),E=vm.runInContext('CINE_ENGINE',ctx);
assert.equal(D.filmes.length,200);assert.equal(D.regras.length,45);assert.equal(D.perfis.length,25);
for(const genre of ['acao','romance']){
 set('genero',genre);
 assert(q().some(x=>x.key==='foco'),'subgênero deve existir');
 assert(!q().some(x=>x.key==='formato'),'formato não relevante deve ser omitido');
 assert(D.filmes.filter(x=>x.genero===genre).length>=10);
 const foco=opts('foco')[0];set('foco',foco);
 assert(opts('atmosfera').length>1);
 if(genre==='romance')assert(!opts('atmosfera').includes('sombria'));
 const candidates=E.recomendar({genero:genre,foco,epoca:'qualquer',atmosfera:'indiferente',narrativa:'indiferente',ritmo:'indiferente',reviravolta:'indiferente'});
 assert(candidates.total>0);
 assert(candidates.lista.every(x=>x.genero===genre));
}
set('genero','comedia');set('foco','humor_leve');
assert(!opts('atmosfera').includes('sombria'));assert(!opts('atmosfera').includes('tensa'));
assert(!opts('narrativa').includes('misterio'));
assert(fs.readFileSync(path.join(dir,'index.html'),'utf8').includes('metadados.js'));
assert(js.includes('renderFilm()')&&js.includes('openFilm(el.dataset.film'));
console.log('TESTES 4.3 APROVADOS: 200 filmes, 70 regras, Ação, Romance, comédia adaptativa e fichas.');
