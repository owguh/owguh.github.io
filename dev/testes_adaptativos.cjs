'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict'),path=require('path');
const p=path.join(__dirname,'..');
const js=fs.readFileSync(path.join(p,'aplicativo.js'),'utf8');
const prefix=js.slice(0,js.indexOf('function renderIntro()'));
const ctx=vm.createContext({document:{querySelector:()=>({})},console});
for(const f of ['dados.js','motor.js'])vm.runInContext(fs.readFileSync(path.join(p,f),'utf8'),ctx,{filename:f});
vm.runInContext(prefix,ctx);
const q=()=>JSON.parse(vm.runInContext('JSON.stringify(questions())',ctx));
const set=(k,v)=>vm.runInContext(`setAnswer(${JSON.stringify(k)},${JSON.stringify(v)})`,ctx);
const options=k=>q().find(x=>x.key===k)?.opts.map(x=>x[1]);
set('genero','comedia');set('foco','humor_leve');
assert(!q().some(x=>x.key==='formato'),'comédia não pergunta live-action');
assert(!options('atmosfera').includes('sombria'));
assert(!options('atmosfera').includes('tensa'));
assert(!options('narrativa').includes('misterio'));
assert(!q().some(x=>x.key==='reviravolta'));
set('atmosfera','leve');set('narrativa','aventura');
set('foco','satira_social');
assert(!vm.runInContext('Object.hasOwn(state.answers,"narrativa")',ctx));
assert(!vm.runInContext('Object.hasOwn(state.answers,"atmosfera")',ctx));
assert(options('atmosfera').includes('reflexiva'));
assert(options('narrativa').includes('critica_social'));
set('genero','terror');set('foco','sobrenatural');
assert(options('atmosfera').includes('tensa'));
assert(!options('atmosfera').includes('leve'));
assert(!options('narrativa').includes('aventura'));
assert(q().some(x=>x.key==='reviravolta'));
set('genero','suspense');assert(options('narrativa').includes('misterio'));
set('genero','animacao');assert(options('atmosfera').includes('fantastica'));
set('genero','qualquer');assert(q().some(x=>x.key==='formato'));
const D=vm.runInContext('CINE_DATA',ctx),E=vm.runInContext('CINE_ENGINE',ctx);
const prefs={genero:'comedia',foco:'humor_leve',epoca:'recente',atmosfera:'leve',narrativa:'aventura',ritmo:'moderado'};
const r=E.recomendar(prefs);assert(r.lista.every(f=>f.ano>=2018));
console.log('TESTES ADAPTATIVOS APROVADOS: humor, subgênero, atmosfera, narrativa, época, exclusão de perguntas e resultados.');
